"""Backtest, score, and explain: gold -> model tables + docs/results.md."""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from leadscore import lakehouse as lh
from leadscore import modeling as md

SCORE_MONTHS = ["2010-09-01", "2010-10-01", "2010-11-01"]

spark = lh.get_spark()
spark.sparkContext.setLogLevel("ERROR")
gold = lh.read_table(spark, "gold_lead_features").toPandas()
gold["call_month_start"] = pd.to_datetime(gold["call_month_start"])

# 1. Rolling monthly backtest -------------------------------------------------
bt = md.run_backtest(gold)
calib = md.calibration_table(bt.predictions)
print(bt.summary.round(3).to_string(index=False))

# 2. Score the latest months with reason codes --------------------------------
scored = pd.concat([md.score_month(gold, pd.Timestamp(m)) for m in SCORE_MONTHS], ignore_index=True)
lift = md.lift_table(scored)

# 3. Persist to the lakehouse -------------------------------------------------
to_spark = lambda df: spark.createDataFrame(df.assign(**{  # noqa: E731
    c: df[c].dt.date for c in df.columns if pd.api.types.is_datetime64_any_dtype(df[c])}))
lh.write_table(to_spark(bt.monthly), "gold_model_backtest")
lh.write_table(to_spark(bt.summary), "gold_model_summary")
lh.write_table(to_spark(calib), "gold_model_calibration")
lh.write_table(to_spark(scored), "gold_lead_scores")
lh.write_table(to_spark(lift), "gold_model_lift")

# 4. Optional experiment tracking (MLflow is built into Fabric) ---------------
try:
    import mlflow
    mlflow.set_experiment("lead-prioritization")
    with mlflow.start_run(run_name="monthly-backtest"):
        mlflow.log_params({"champion": "logistic_regression", "retraining": "monthly, expanding window"})
        for _, r in bt.summary.iterrows():
            for k in ("auc", "top20_capture"):
                mlflow.log_metric(f"{r['model']}_{k}", float(r[k]))
except Exception as exc:  # tracking must never break the pipeline
    print(f"MLflow logging skipped: {exc}")

# 5. Results doc + chart ------------------------------------------------------
docs = Path("docs"); docs.mkdir(exist_ok=True)
pivot = bt.monthly.pivot(index="month", columns="model", values="auc")
fig, ax = plt.subplots(figsize=(8, 3.6))
for col, style in [("logistic_regression", "-o"), ("lightgbm", "--"), ("logistic_never_retrained", "-x"), ("seller_rule", ":")]:
    ax.plot(pivot.index, pivot[col], style, label=col.replace("_", " "), markersize=4)
ax.axhline(0.5, color="grey", lw=0.8)
ax.set_ylabel("AUC within month"); ax.set_title("Out-of-time ranking quality by month")
ax.legend(fontsize=8, ncol=2); fig.autofmt_xdate(); fig.tight_layout()
fig.savefig(docs / "backtest_auc.png", dpi=150)

pct = lambda v: f"{v:.1%}"  # noqa: E731
summ = bt.summary.set_index("model")
lines = [
    "# Results (generated by scripts/run_model.py)", "",
    f"Rolling monthly backtest: {int(summ.loc['logistic_regression', 'months'])} months, each scored by a model trained only on earlier months.", "",
    "| Model | AUC (within month) | Top 20% of calls captures | Brier |", "|---|---|---|---|",
]
for m, r in summ.iterrows():
    brier = "n/a" if pd.isna(r["brier"]) else f"{r['brier']:.3f}"
    lines.append(f"| {m.replace('_', ' ')} | {r['auc']:.3f} | {pct(r['top20_capture'])} of conversions | {brier} |")
lines += ["", "![AUC by month](backtest_auc.png)", "", "## Calibration (pooled out-of-time predictions)", "",
          "| Score decile | Leads | Avg predicted | Actual rate |", "|---|---|---|---|"]
lines += [f"| {int(r.decile)} | {int(r.leads)} | {pct(r.avg_predicted)} | {pct(r.actual_rate)} |" for r in calib.itertuples()]
lines += ["", f"## Lift on the latest {len(SCORE_MONTHS)} months ({len(scored)} leads)", "",
          "| Priority decile | Cumulative share of leads | Cumulative share of conversions | Lift |", "|---|---|---|---|"]
lines += [f"| {int(r.priority_decile)} | {pct(r.cum_leads_share)} | {pct(r.cum_conversions_share)} | {r.lift:.2f}x |" for r in lift.itertuples()]
lines += ["", "## Sample of the ranked call list", "",
          "| Lead | Month | Score | Reason 1 | Reason 2 | Reason 3 |", "|---|---|---|---|---|---|"]
for r in scored.head(8).itertuples():
    lines.append(f"| {r.lead_id} | {str(r.score_month)[:7]} | {r.score:.2f} | {r.reason_1 or ''} | {r.reason_2 or ''} | {r.reason_3 or ''} |")
(docs / "results.md").write_text("\n".join(lines) + "\n")
print("done")
